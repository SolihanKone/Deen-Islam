  final double longitude;

  PrayerCoordinates get coords =>
      PrayerCoordinates(latitude: latitude, longitude: longitude);

  String get label => '$name, $country';
}

/// Offline city list for prayer times when GPS is off or denied.
abstract final class PrayerCities {
  static PrayerCity? byId(String? id) {
    if (id == null || id.isEmpty) return null;
    for (final city in all) {
      if (city.id == id) return city;
    }
    return null;
  }

  static List<PrayerCity> search(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return all;
    return [
      for (final city in all)
        if (city.name.toLowerCase().contains(q) ||
            city.country.toLowerCase().contains(q) ||
            city.id.contains(q))
          city,
    ];
  }

  static PrayerCity? nearest(double lat, double lng, {double maxKm = 80}) {
    PrayerCity? best;
    var bestKm = maxKm;
    for (final city in all) {
      final km = _km(lat, lng, city.latitude, city.longitude);
      if (km <= bestKm) {
        bestKm = km;
        best = city;
      }
    }
    return best;
  }

  static double _km(double lat1, double lon1, double lat2, double lon2) {
    const r = 6371.0;
    const p = math.pi / 180;
    final a =
        0.5 -
        math.cos((lat2 - lat1) * p) / 2 +
        math.cos(lat1 * p) *
            math.cos(lat2 * p) *
            (1 - math.cos((lon2 - lon1) * p)) /
            2;
    return 2 * r * math.asin(math.sqrt(a));
  }

